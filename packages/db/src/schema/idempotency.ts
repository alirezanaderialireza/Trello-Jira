import { pgTable, varchar, jsonb, timestamp, index } from "drizzle-orm/pg-core";

// ============================================================================
// 🗄️ Idempotency Keys Table
// ============================================================================
// وظیفه: ذخیره پاسخ‌های Idempotent برای mutationها
// این جدول تضمین می‌کند که اجرای مجدد یک mutation با همان `mutationId`
// نتیجه یکسانی تولید کند.
// ============================================================================

export const idempotencyKeys = pgTable(
  "idempotency_keys",
  {
    // =========================================================================
    // 🔹 Primary Key (Client-Supplied)
    // =========================================================================
    mutationId: varchar("mutation_id", { length: 128 }).primaryKey(), // cuid یا uuid کلاینت

    // =========================================================================
    // 🔹 Stored Response
    // =========================================================================
    response: jsonb("response").notNull(),          // پاسخ ذخیره شده برای Idempotency

    // =========================================================================
    // 🔹 Schema Versioning
    // =========================================================================
    schemaVersion: varchar("schema_version", { length: 32 }).notNull(), // ورژن schema پاسخ

    // =========================================================================
    // 🔹 Lifecycle
    // =========================================================================
    createdAt: timestamp("created_at").notNull().defaultNow(),
  },
  (table) => ({
    // =========================================================================
    // 🔹 Indexes
    // =========================================================================
    createdIdx: index("idempotency_created_idx").on(table.createdAt),
  })
);

// =============================================================================
// Types
// =============================================================================
export type IdempotencyKey = typeof idempotencyKeys.$inferSelect;
export type NewIdempotencyKey = typeof idempotencyKeys.$inferInsert;